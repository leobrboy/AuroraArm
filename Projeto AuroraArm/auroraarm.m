% AuroraArm academic model and evidence script (GNU Octave, base functions).
clear; close all; clc;

R=0.8; L=1.2e-3; Kt=0.085; Ke=0.085; J=4.2e-4; b=1.5e-4;
N=100; Vmax=48; imax=8; Ts=2e-3; tau_load=0.25;
omega_crit=450; payload=2; arm=0.35;
A=[-R/L, -Ke/L, 0; Kt/J, -b/J, 0; 0, 1, 0];
B=[1/L;0;0]; C=[0 0 1/N]; D=0;
Co=[B A*B A*A*B]; Ob=[C;C*A;C*A*A];
tau_e=L/R; tau_m=J/(b+Kt*Ke/R);
Iop=tau_load/Kt; Vop=R*Iop+Ke*omega_crit;
omega_joint=omega_crit/N; v_eff=arm*omega_joint; v_mm_s=1000*v_eff;
omega_safe=0.250/arm*N;
ev=eig(A);

% Deterministic exhaustive enumeration in 1 ms bins. Sensor delay 0..20 ms;
% one missed 2 ms supervisor cycle is represented by 0 or 2 ms.
delay_ms=(0:20)'; jitter_ms=[0 2]; latency=zeros(numel(delay_ms),2);
for k=1:numel(delay_ms), latency(k,:)=delay_ms(k)+jitter_ms; end
worst_ms=max(latency(:)); deadline_ms=100;

% Finite-state security supervisor: 1=MOVING, 2=STOPPING, 3=STOPPED,
% 4=FIELD_CLEAR, 5=REARMED. Events: obstacle, zero_confirmed, field_clear,
% operator_rearm, resume. Exhaustively enumerate every event string of length 5.
states={'MOVING','STOPPING','STOPPED','FIELD_CLEAR','REARMED'}; transitions=[];
for s=1:5
 for e=1:5
  ns=s;
  if s==1 && e==1, ns=2; elseif s==2 && e==2, ns=3;
  elseif s==3 && e==3, ns=4; elseif s==4 && e==4, ns=5;
  elseif s==5 && e==5, ns=1; end
  transitions=[transitions; s e ns]; %#ok<AGROW>
 end
end
sequences=5^5; auto_restart_violations=0; state_coverage=false(5,1);
transition_coverage=false(5,5); rearm_path_seen=false;
for code=0:sequences-1
 s=1; q=code; rearmed=false;
 for k=1:5
  e=mod(q,5)+1; q=floor(q/5); ns=transitions(transitions(:,1)==s & transitions(:,2)==e,3);
  state_coverage(s)=true; transition_coverage(s,e)=true;
  if s==3 && ns==1, auto_restart_violations+=1; end
  if e==4, rearmed=true; end
  s=ns;
 end
 if s==1 && rearmed, rearm_path_seen=true; end
end
% Reproduce a concrete counterexample in a faulty preliminary transition table.
prelim_state=1; prelim_events=[1 2 5];
for e=prelim_events
 ns=transitions(transitions(:,1)==prelim_state & transitions(:,2)==e,3);
 if prelim_state==3 && e==5, ns=1; end % faulty automatic-resume transition
 prelim_state=ns;
end
prelim_counterexample_found=(prelim_state==1);
preliminary_counterexample='obstacle -> torque_zero_confirmed -> resume (MOVING without field_clear/rearm)';

% Emit generated controller C from this model's constants (saturating voltage).
if ~exist('generated','dir'), mkdir('generated'); end
phi=exp(-R*Ts/L); gamma_i=(1-phi)/R;
fid=fopen('generated/auroraarm_controller.c','w');
fprintf(fid,['/* Generated by auroraarm.m; REQ-CTRL-AA-001..004; SI units. */\n' ...
 '/* Academic reference only. Safety functions require independent hardware. */\n' ...
 '#include <math.h>\n#define AA_TS %.9g\n#define AA_VMAX %.9g\n#define AA_IMAX %.9g\n' ...
 '#define AA_PHI %.9g\n#define AA_GAMMA_I %.9g\n#define AA_KE %.9g\n#define AA_SAFE_OMEGA %.9g\n' ...
 'float auroraarm_voltage(float theta_ref,float theta,float *integrator,\n' ...
 ' float kp,float ki,float kd,float dtheta,float current,float omega) {\n' ...
 ' float e=theta_ref-theta; float u0=kp*e+ki*(*integrator)-kd*dtheta;\n' ...
 ' float u=fmaxf(-AA_VMAX,fminf(AA_VMAX,u0));\n' ...
 ' /* Exact one-step armature-current clamp, assuming omega constant this sample. */\n' ...
 ' float umax=(AA_IMAX-AA_PHI*current)/AA_GAMMA_I+AA_KE*omega;\n' ...
 ' float umin=(-AA_IMAX-AA_PHI*current)/AA_GAMMA_I+AA_KE*omega;\n' ...
 ' u=fmaxf(umin,fminf(umax,u));\n' ...
 ' /* Conditional integration anti-windup for voltage/current saturation. */\n' ...
 ' if ((fabsf(u-u0)<1e-6f) || (u<u0 && e<0) || (u>u0 && e>0)) *integrator += AA_TS*e;\n' ...
 ' return u; }\n' ...
 'float auroraarm_safe_speed_ref(float omega_ref,int collaborative_zone) {\n' ...
 ' if (!collaborative_zone) return omega_ref;\n' ...
 ' return fmaxf(-AA_SAFE_OMEGA,fminf(AA_SAFE_OMEGA,omega_ref)); }\n'],Ts,Vmax,imax,phi,gamma_i,Ke,omega_safe);
fclose(fid);

% Closed-loop position step simulation: 0.1 rad at joint, ZOH exact plant,
% current limit imposed by predicting the next discrete motor current.
M=expm([A B;zeros(1,4)]*Ts); Ad=M(1:3,1:3); Bd=M(1:3,4);
kp=800; ki=400; kd=45; ref_step=0.1; nstep=15000; x=zeros(3,1); integ=0;
ypos=zeros(nstep,1); ulog=ypos; ilog=ypos;
for k=1:nstep
 e=ref_step-x(3)/N; u0=kp*e+ki*integ-kd*x(2)/N;
 u=max(-Vmax,min(Vmax,u0));
 umax_i=(imax-Ad(1,:)*x)/Bd(1); umin_i=(-imax-Ad(1,:)*x)/Bd(1);
 u=max(umin_i,min(umax_i,u));
 if (abs(u-u0)<1e-6)||(u<u0 && e<0)||(u>u0 && e>0), integ+=Ts*e; end
 x=Ad*x+Bd*u+[0;-Kt/J*tau_load*Ts;0];
 ypos(k)=x(3)/N; ulog(k)=u; ilog(k)=x(1);
end
overshoot_pct=max(0,(max(ypos)-ref_step)/ref_step*100);
outside=find(abs(ypos-ref_step)>0.02*ref_step,1,'last');
if isempty(outside), settle_ms=0; else, settle_ms=outside*Ts*1000; end
steady_err=abs(ypos(end)-ref_step);

% Compiled SIL: C harness executes the generated function on identical vectors.
if ~exist('tests','dir'), mkdir('tests'); end
n_sil=10001; sil_ref=0.1*sin((0:n_sil-1)'*0.013);
sil_theta=0.04*cos((0:n_sil-1)'*0.009); sil_cur=7.5*sin((0:n_sil-1)'*0.021);
sil_omega=100*cos((0:n_sil-1)'*0.017); sil_dth=2*cos((0:n_sil-1)'*0.013);
vf=fopen('tests/sil_vectors.csv','w');
for k=1:n_sil, fprintf(vf,'%.9g,%.9g,%.9g,%.9g,%.9g\n',sil_ref(k),sil_theta(k),sil_cur(k),sil_omega(k),sil_dth(k)); end
fclose(vf);
cmd='gcc -O2 generated/auroraarm_controller.c tests/sil_harness.c -lm -o tests/sil_harness.exe';
[compile_status,compile_msg]=system(cmd);
if compile_status~=0, error('SIL C compilation failed: %s',compile_msg); end
[sil_status,sil_msg]=system('.\\tests\\sil_harness.exe');
if sil_status~=0, error('SIL harness failed: %s',sil_msg); end
sil_out=load('tests/sil_output.csv');
sil_model=zeros(n_sil,1); sil_int=0;
for k=1:n_sil
 e=sil_ref(k)-sil_theta(k); u0=kp*e+ki*sil_int-kd*sil_dth(k);
 u=max(-Vmax,min(Vmax,u0));
 umax_i=(imax-phi*sil_cur(k))/gamma_i+Ke*sil_omega(k);
 umin_i=(-imax-phi*sil_cur(k))/gamma_i+Ke*sil_omega(k);
 u=max(umin_i,min(umax_i,u)); sil_model(k)=u;
 if (abs(u-u0)<1e-5)||(u<u0&&e<0)||(u>u0&&e>0), sil_int+=Ts*e; end
end
err_sil=max(abs(sil_model-sil_out));
% Reproducible subset of golden vectors for the ARM Cortex-M4 emulator test.
arm_idx=1:5:n_sil; arm_fid=fopen('tests/m4_vectors.h','w'); arm_integral=0;
fprintf(arm_fid,'#ifndef AURORAARM_M4_VECTORS_H\n#define AURORAARM_M4_VECTORS_H\n');
fprintf(arm_fid,'typedef struct { float ref, theta, current, omega, dtheta, expected; } M4Vector;\n');
fprintf(arm_fid,'static const M4Vector m4_vectors[] = {\n');
for k=arm_idx
 e= sil_ref(k)-sil_theta(k); u0=kp*e+ki*arm_integral-kd*sil_dth(k);
 u=max(-Vmax,min(Vmax,u0));
 umax_i=(imax-phi*sil_cur(k))/gamma_i+Ke*sil_omega(k);
 umin_i=(-imax-phi*sil_cur(k))/gamma_i+Ke*sil_omega(k);
 u=max(umin_i,min(umax_i,u));
 fprintf(arm_fid,' {%.9e,%.9e,%.9e,%.9e,%.9e,%.9e},\n',sil_ref(k),sil_theta(k),sil_cur(k),sil_omega(k),sil_dth(k),u);
 if (abs(u-u0)<1e-6)||(u<u0&&e<0)||(u>u0&&e>0), arm_integral+=Ts*e; end
end
fprintf(arm_fid,'};\n#define M4_VECTOR_COUNT (sizeof(m4_vectors)/sizeof(m4_vectors[0]))\n#endif\n');
fclose(arm_fid);
[obj_status,obj_msg]=system('gcc -Os -c generated/auroraarm_controller.c -o tests/controller.o');
if obj_status~=0, error('Controller object compilation failed: %s',obj_msg); end
[size_status,size_msg]=system('"C:\\Program Files\\GNU Octave\\Octave-11.3.0\\mingw64\\bin\\size.exe" tests/controller.o');
if size_status~=0, size_msg='Object size utility unavailable'; end

fid=fopen('results.txt','w');
fprintf(fid,'A =\n'); fprintf(fid,'%.9g %.9g %.9g\n',A');
fprintf(fid,'B =\n'); fprintf(fid,'%.9g\n',B);
fprintf(fid,'Cj = [0 0 %.9g], D = 0\n',1/N);
fprintf(fid,'rank controllability = %d / 3\n',rank(Co));
fprintf(fid,'rank observability = %d / 3 (position output)\n',rank(Ob));
fprintf(fid,'eigenvalues =\n'); fprintf(fid,'%.9g%+.9gi\n',[real(ev),imag(ev)]');
fprintf(fid,'tau_e = %.9g s; tau_m = %.9g s; samples/tau_m = %.9g\n',tau_e,tau_m,tau_m/Ts);
fprintf(fid,'operating point: I = %.9g A, V = %.9g V, voltage headroom = %.9g V, current headroom = %.9g A\n',Iop,Vop,Vmax-Vop,imax-Iop);
fprintf(fid,'critical endpoint speed = %.9g mm/s; safe speed cap for 250 mm/s = %.9g rad/s motor\n',v_mm_s,omega_safe);
fprintf(fid,'REQ-SAFE-AA-001 worst enumerated logical latency = %.9g ms; deadline = %.9g ms; PASS (torque-zero command only)\n',worst_ms,deadline_ms);
fprintf(fid,'REQ-SAFE-AA-001 conservative budget including one supervisor cycle = %.9g ms; PASS logically, physical stop unproven\n',worst_ms+Ts*1000);
if auto_restart_violations==0, restart_status='PASS'; else, restart_status='FAIL'; end
fprintf(fid,'REQ-SAFE-AA-002 no automatic restart: %s (transition invariant); sequences checked = %d\n', restart_status,sequences);
fprintf(fid,'Supervisor coverage: %d/5 states; %d/25 state-event pairs; liveness witness = %d; preliminary defect counterexample found = %d: %s\n',sum(state_coverage),sum(transition_coverage(:)),rearm_path_seen,prelim_counterexample_found,preliminary_counterexample);
fprintf(fid,'REQ-SAFE-AA-003 conditional liveness: field_clear -> operator_rearm -> resume reaches MOVING = %d\n',rearm_path_seen);
if v_mm_s<=250, speed_status='PASS'; else, speed_status='FAIL AT CRITICAL POINT'; end
fprintf(fid,'REQ-SAFE-AA-004 critical speed = %.9g mm/s vs limit 250 mm/s: %s; safe-mode motor cap = %.9g rad/s\n',v_mm_s,speed_status,omega_safe);
fprintf(fid,'CTRL step: reference = %.3g rad joint; Kp=%.3g Ki=%.3g Kd=%.3g; overshoot=%.6g%%; settling=%.6g ms; final error=%.9g rad\n',ref_step,kp,ki,kd,overshoot_pct,settle_ms,steady_err);
fprintf(fid,'CTRL constraints in ZOH simulation: peak |V|=%.9g V <=48; peak |i|=%.9g A <=8\n',max(abs(ulog)),max(abs(ilog)));
fprintf(fid,'REQ-HW-001 500 Hz loop: Ts=%.3g s; host timing proxy in tests/host_timing.txt; Cortex-M4 WCET <200 us and 256 KB remain to be verified on target\n',Ts);
fprintf(fid,'Host object-size report (not target-linked firmware image): %s\n',strtrim(size_msg));
fprintf(fid,'REQ-SAFE-AA-004 generated safe-speed reference limiter tested by compiled C harness at 450 rad/s request\n');
if err_sil<=1e-4, sil_status='PASS'; else, sil_status='FAIL'; end
fprintf(fid,'SIL compiled C max absolute output difference = %.9g V; float epsilon = %.9g; acceptance tolerance = 1e-4 V; %s\n',err_sil,eps('single'),sil_status);
fclose(fid);

% State-space analytical operating point and eigenvalue output for review.
disp(fileread('results.txt'));
if ~exist('figures','dir'), mkdir('figures'); end
figure(1); bar([Iop imax-Iop Vop Vmax-Vop]); grid on;
set(gca,'xticklabel',{'I op (A)','I margin (A)','V op (V)','V margin (V)'});
ylabel('value'); title('AuroraArm operating point and actuator headroom');
print('figures/headroom.png','-dpng','-r140');
figure(2); t=(1:nstep)'*Ts; plot(t,ypos,'LineWidth',1.2); hold on; plot(t,ref_step+0*t,'--'); grid on;
xlabel('Time (s)'); ylabel('Joint position (rad)'); title('0.1 rad position step response');
print('figures/position_step.png','-dpng','-r140');

% End-to-end software-only model with explicit sensor/drive quantization,
% load variation, and one-cycle actuator command delay.
run('tests/software_only_scenarios.m');

